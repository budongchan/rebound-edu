export function getCourseEnrollmentStatus(course) {
  if (course.enrollmentStatus && COURSE_ENROLLMENT_STATUS[course.enrollmentStatus]) {
    return COURSE_ENROLLMENT_STATUS[course.enrollmentStatus];
  }
  if (course.enrollmentStatus && Object.values(COURSE_ENROLLMENT_STATUS).includes(course.enrollmentStatus)) {
    return course.enrollmentStatus;
  }
  if (course.enrollmentClosed) return COURSE_ENROLLMENT_STATUS.closed;
  if (course.enrollmentWaiting) return COURSE_ENROLLMENT_STATUS.waiting;
  return COURSE_ENROLLMENT_STATUS.available;
}

export function getCourseDeliveryLabel(course) {
  return COURSE_DELIVERY_LABEL[course.delivery] || course.delivery || "";
}

export function getCategory(key) {
  return CATEGORIES.find((c) => c.key === key) || null;
}
export function coursesByCategory(key) {
  return COURSES.filter((c) => c.category === key && !c.hiddenFromCatalog);
}

export function visibleCourses() {
  return COURSES.filter((c) => !c.hiddenFromCatalog);
}

